create type public.app_role as enum ('admin', 'staff');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  created_at timestamptz not null default now()
);
grant select, update on public.profiles to authenticated;
grant all on public.profiles to service_role;
alter table public.profiles enable row level security;

create table public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade not null,
  role app_role not null,
  unique (user_id, role)
);
grant select on public.user_roles to authenticated;
grant all on public.user_roles to service_role;
alter table public.user_roles enable row level security;

create or replace function public.has_role(_user_id uuid, _role app_role)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.user_roles where user_id = _user_id and role = _role)
$$;

create or replace function public.is_member(_user_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.user_roles where user_id = _user_id)
$$;

create policy "members read profiles" on public.profiles for select to authenticated using (public.is_member(auth.uid()) or id = auth.uid());
create policy "own profile update" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create policy "read own role or admin all" on public.user_roles for select to authenticated using (user_id = auth.uid() or public.has_role(auth.uid(),'admin'));

-- admin role management via RPC
create or replace function public.set_user_role(_user_id uuid, _role app_role)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.has_role(auth.uid(), 'admin') then raise exception 'Only admins can change roles'; end if;
  if _user_id = auth.uid() and _role <> 'admin' then raise exception 'You cannot demote yourself'; end if;
  delete from public.user_roles where user_id = _user_id;
  insert into public.user_roles(user_id, role) values (_user_id, _role);
end $$;
grant execute on function public.set_user_role(uuid, app_role) to authenticated;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, email, full_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name'));
  if not exists (select 1 from public.user_roles where role = 'admin') then
    insert into public.user_roles(user_id, role) values (new.id, 'admin');
  else
    insert into public.user_roles(user_id, role) values (new.id, 'staff');
  end if;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create table public.records (
  id uuid primary key default gen_random_uuid(),
  serial_no integer generated by default as identity unique,
  sponsor_name text not null,
  sponsor_id text,
  phone text,
  worker_name text,
  passport_no text,
  visa_no text,
  musaned_no text,
  city text,
  medical text not null default 'PENDING',
  payment_state text not null default 'PENDING',
  visa_status text not null default 'WKALA',
  amount numeric(12,2) not null default 0,
  currency text not null default 'SAR',
  transaction_date date,
  processing_date date,
  airport text,
  reserved text,
  notes text,
  created_by uuid,
  created_by_email text,
  updated_by uuid,
  updated_by_email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint payment_chk check (payment_state in ('PAID','PENDING','PARTIAL','UNPAID','REFUNDED')),
  constraint medical_chk check (medical in ('FIT','UNFIT','PENDING')),
  constraint visa_chk check (visa_status in ('WKALA','EMBASSY','VISA STAMP','TRIB','BIOMETRIC','ARRIVED','CANCELLED')),
  constraint currency_chk check (currency in ('SAR','USD','ETB','EUR')),
  constraint amount_chk check (amount >= 0)
);
grant select, insert, update, delete on public.records to authenticated;
grant all on public.records to service_role;
alter table public.records enable row level security;
create policy "members read" on public.records for select to authenticated using (public.is_member(auth.uid()));
create policy "members insert" on public.records for insert to authenticated with check (public.is_member(auth.uid()));
create policy "members update" on public.records for update to authenticated using (public.is_member(auth.uid())) with check (public.is_member(auth.uid()));
create policy "admins delete" on public.records for delete to authenticated using (public.has_role(auth.uid(),'admin'));

-- stamps + financial lock enforcement
create or replace function public.records_guard()
returns trigger language plpgsql security definer set search_path = public as $$
declare is_admin boolean := public.has_role(auth.uid(), 'admin');
begin
  if auth.uid() is null then return new; end if;
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.created_by_email := auth.jwt()->>'email';
    if not is_admin and new.payment_state = 'PAID' then
      raise exception 'Only admins can mark a record as PAID';
    end if;
  else
    new.created_by := old.created_by; new.created_by_email := old.created_by_email; new.created_at := old.created_at;
    if not is_admin then
      if new.payment_state is distinct from old.payment_state and (old.payment_state = 'PAID' or new.payment_state = 'PAID') then
        raise exception 'Only admins can change a PAID payment state';
      end if;
      if old.payment_state = 'PAID' and (new.amount is distinct from old.amount or new.currency is distinct from old.currency) then
        raise exception 'Financial fields are locked on PAID records — ask an admin';
      end if;
    end if;
  end if;
  new.updated_by := auth.uid();
  new.updated_by_email := auth.jwt()->>'email';
  new.updated_at := now();
  return new;
end $$;
create trigger records_guard before insert or update on public.records for each row execute function public.records_guard();

create table public.audit_log (
  id bigint generated always as identity primary key,
  record_id uuid,
  serial_no integer,
  action text not null,
  actor_id uuid,
  actor_email text,
  changes jsonb,
  created_at timestamptz not null default now()
);
grant select on public.audit_log to authenticated;
grant all on public.audit_log to service_role;
alter table public.audit_log enable row level security;
create policy "members read audit" on public.audit_log for select to authenticated using (public.is_member(auth.uid()));

create or replace function public.records_audit()
returns trigger language plpgsql security definer set search_path = public as $$
declare diff jsonb := '{}'::jsonb; k text; o jsonb; n jsonb;
begin
  if tg_op = 'INSERT' then
    insert into public.audit_log(record_id, serial_no, action, actor_id, actor_email, changes)
    values (new.id, new.serial_no, 'create', auth.uid(), auth.jwt()->>'email', null);
    return new;
  elsif tg_op = 'UPDATE' then
    o := to_jsonb(old); n := to_jsonb(new);
    for k in select jsonb_object_keys(n) loop
      if k not in ('updated_at','updated_by','updated_by_email') and (o->k) is distinct from (n->k) then
        diff := diff || jsonb_build_object(k, jsonb_build_object('from', o->k, 'to', n->k));
      end if;
    end loop;
    if diff <> '{}'::jsonb then
      insert into public.audit_log(record_id, serial_no, action, actor_id, actor_email, changes)
      values (new.id, new.serial_no, 'update', auth.uid(), auth.jwt()->>'email', diff);
    end if;
    return new;
  else
    insert into public.audit_log(record_id, serial_no, action, actor_id, actor_email, changes)
    values (old.id, old.serial_no, 'delete', auth.uid(), auth.jwt()->>'email', jsonb_build_object('worker_name', old.worker_name, 'sponsor_name', old.sponsor_name));
    return old;
  end if;
end $$;
create trigger records_audit after insert or update or delete on public.records for each row execute function public.records_audit();